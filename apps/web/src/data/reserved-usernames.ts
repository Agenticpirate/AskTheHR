export function foldUsername(value: string): string {
  return value
    .toLowerCase()
    .replace(/_/g, "")
    .replace(/0/g, "o")
    .replace(/[1li]/g, "i");
}

const EXACT = new Set(RESERVED_USERNAMES.map((n) => n.toLowerCase()));
const FOLDED = new Set(RESERVED_USERNAMES.map(foldUsername));

export function isReservedUsername(username: string): boolean {
  const u = username.toLowerCase();
  if (EXACT.has(u)) return true;
  return FOLDED.has(foldUsername(u));
}
